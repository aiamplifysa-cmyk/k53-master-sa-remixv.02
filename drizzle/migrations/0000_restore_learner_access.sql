CREATE OR REPLACE FUNCTION public.create_learner_profile() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$ BEGIN INSERT INTO public.profiles(id, display_name) VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'display_name', '')) ON CONFLICT (id) DO NOTHING; RETURN NEW; END; $$;
CREATE OR REPLACE TRIGGER create_learner_profile AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.create_learner_profile();
